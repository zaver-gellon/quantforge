"""Render the study write-up from the results object. No numbers are typed in here."""

from __future__ import annotations

import math


def pct(value, digits: int = 1) -> str:
    if value is None or isinstance(value, bool) or not isinstance(value, (int, float)):
        return "n/a"
    if not math.isfinite(value):
        return "n/a"
    return f"{100.0 * value:.{digits}f}%"


def num(value, digits: int = 2) -> str:
    if value is None or isinstance(value, bool) or not isinstance(value, (int, float)):
        return "n/a"
    if not math.isfinite(value):
        return "n/a"
    return f"{value:.{digits}f}"


def money(value) -> str:
    if value is None or not isinstance(value, (int, float)) or not math.isfinite(value):
        return "n/a"
    return f"${value:,.0f}"


def _row(cells) -> str:
    return "| " + " | ".join(str(cell) for cell in cells) + " |"


def _metrics_row(name, metrics: dict) -> str:
    worst = metrics.get("worst_year")
    worst_ret = metrics.get("worst_year_return")
    worst_txt = "n/a" if worst is None else f"{worst} {pct(worst_ret)}"
    return _row([
        name,
        pct(metrics.get("cagr")),
        pct(metrics.get("vol")),
        num(metrics.get("sharpe")),
        pct(metrics.get("max_drawdown")),
        worst_txt,
        num(metrics.get("turnover_per_year"), 1),
        num(metrics.get("ir_t")),
        num(metrics.get("psr"), 2),
        num(metrics.get("dsr"), 2),
    ])


def render_report(results: dict) -> str:
    sample = results["sample"]
    lines = [
        "# SPY core plus a leveraged trend sleeve",
        "",
        "Generated by `python studies/spy_upro_trend/run.py`. Figures in this file come from that run.",
        "",
        results["protocol_md"].strip(),
        "",
        "## Sample",
        "",
        f"- Sessions: {sample['start']} to {sample['end']} ({sample['n_days']} days, {sample['years']:.1f} years at 252 sessions/year).",
        f"- One-way cost on SPY, SSO, and UPRO: {results['costs_one_way_bps']:.1f} bps. Cash is not charged.",
        f"- Financing spread: {pct(results['financing_spread'])} annual over the lagged 13-week T-bill. T-bill unit: {results['irx_unit']}.",
        f"- Trials counted toward deflation: {results['n_trials']}. "
        f"Expected maximum |t| under an independent null: {num(results['multiple_testing_bar_t'])}. "
        f"Cross-trial dispersion of daily Sharpe: {num(results['sharpe_dispersion_daily'], 4)}.",
        "",
        "## Leveraged ETF validation",
        "",
        "The synthetic fund is not used where a listed total-return series exists in the validation columns. "
        "The strategy backtest itself uses the synthetic path for the full sample so 2000–2008 is defined, "
        "then repeats the desk mix on a path that switches to the listed ETF once it has a prior close.",
        "",
        _row(["ETF", "overlap", "years", "actual CAGR", "synth CAGR", "corr", "TE", "trend synth", "trend stitched"]),
        _row(["---"] * 9),
    ]
    for row in results["validation"]:
        lines.append(_row([
            row["etf"],
            f"{row.get('start', 'n/a')} ({row.get('n_days', 0)}d)",
            num(row.get("years"), 1),
            pct(row.get("actual_cagr")),
            pct(row.get("synthetic_cagr")),
            num(row.get("daily_corr"), 4),
            pct(row.get("tracking_error")),
            pct(row.get("trend_synth_cagr")),
            pct(row.get("trend_stitched_cagr")),
        ]))
    lines += [
        "",
        "`trend synth` / `trend stitched` are a 100% sleeve, SMA 200, 2% band, daily evaluation, "
        "measured on the overlap only. Stitched means listed returns after the fund exists.",
        "",
        "## Headline results",
        "",
        _row(["strategy", "CAGR", "vol", "Sharpe", "max DD", "worst year", "turnover/yr", "IR t vs SPY", "PSR", "DSR"]),
        _row(["---"] * 10),
    ]
    for name, metrics in results["headline"]:
        lines.append(_metrics_row(name, metrics))
    lines += [
        "",
        "Sharpe is excess over the lagged T-bill. IR t is the t-stat of daily active return versus SPY. "
        "PSR is the probability the Sharpe exceeds 0. DSR is that probability versus the ledger's multiple-testing benchmark. "
        "The walk-forward row is the stitched path of variants chosen on past data only.",
        "",
        "## Walk-forward picks",
        "",
        _row(["year", "variant"]),
        _row(["---", "---"]),
    ]
    for year, name in results["walk_forward"]["picks"]:
        lines.append(_row([year, name]))
    lines += [
        "",
        "Years each variant was selected:",
        "",
        _row(["variant", "years selected"]),
        _row(["---", "---"]),
    ]
    for name, count in results["walk_forward"]["frequency"]:
        lines.append(_row([name, count]))
    lines += [
        "",
        "## Subperiods",
        "",
        "CAGR minus SPY CAGR, in percentage points per year.",
        "",
    ]
    labels = results["subperiod_labels"]
    lines.append(_row(["strategy", *labels]))
    lines.append(_row(["---"] * (1 + len(labels))))
    for name, periods in results["subperiods"].items():
        cells = [name]
        for label in labels:
            cell = periods.get(label) or {}
            cells.append(pct(cell.get("excess"), 1).replace("%", "") if cell.get("excess") is not None else "n/a")
        lines.append(_row(cells))
    lines += [
        "",
        "SPY CAGR in each window:",
        "",
        _row(["window", "SPY CAGR"]),
        _row(["---", "---"]),
    ]
    for label, cagr in results["spy_subperiods"]:
        lines.append(_row([label, pct(cagr)]))
    lines += [
        "",
        "## Full-sample ranking inside the grid",
        "",
        "Sorted by full-sample excess Sharpe. This ranking sees the whole sample, so it is not the selection. "
        "The 2013–2026 excess is shown beside it.",
        "",
        _row(["variant", "CAGR", "Sharpe", "max DD", "IR t", "2013-26 excess"]),
        _row(["---"] * 6),
    ]
    for row in results["full_sample_top"]:
        lines.append(_row([
            row["name"],
            pct(row["cagr"]),
            num(row["sharpe"]),
            pct(row["max_drawdown"]),
            num(row["ir_t"]),
            pct(row.get("excess_2013")),
        ]))
    lines += [
        "",
        "## Block bootstrap, $5,000",
        "",
        f"Circular blocks of {results['bootstrap_block']} sessions, "
        f"{results['bootstrap_paths']} paths, seed {results['bootstrap_seed']}. "
        "The benchmark uses the same blocks.",
        "",
        _row(["strategy", "1y median", "1y p10", "1y p90", "1y P(loss)", "1y P(>SPY)", "5y median", "5y p10", "5y p90", "5y P(loss)", "5y P(>SPY)", "5y P(<-30%)"]),
        _row(["---"] * 12),
    ]
    for name, horizons in results["bootstrap"].items():
        y1, y5 = horizons["1y"], horizons["5y"]
        lines.append(_row([
            name,
            money(y1["median"]), money(y1["p10"]), money(y1["p90"]), num(y1["p_loss"], 2), num(y1.get("p_beats_benchmark"), 2),
            money(y5["median"]), money(y5["p10"]), money(y5["p90"]), num(y5["p_loss"], 2), num(y5.get("p_beats_benchmark"), 2),
            num(y5["p_down_30"], 2),
        ]))
    lines += [
        "",
        "## Costs and the next-close fill",
        "",
        "Same decisions. Costs are one-way basis points on SPY and the leveraged fund. "
        "Next-close earns the signal day's whole move with the previous holdings.",
        "",
        _row(["strategy", "0 bp", "3 bp", "5 bp", "10 bp", "next open", "next close"]),
        _row(["---"] * 7),
    ]
    for name, row in results["stress"].items():
        lines.append(_row([
            name,
            pct(row.get("cost_0")),
            pct(row.get("cost_3")),
            pct(row.get("cost_5")),
            pct(row.get("cost_10")),
            pct(row.get("next_open")),
            pct(row.get("next_close")),
        ]))
    lines += [
        "",
        "## Dip-buy overlay",
        "",
        "The 50/50 book with the 2% band. After the rule, only the SPY half switches to synthetic SSO. "
        "The UPRO half is unchanged. Leave at the next open after the first up close, or after five sessions.",
        "",
        _row(["rule", "CAGR", "vol", "Sharpe", "max DD", "worst year", "IR t", "DSR", "trades/yr"]),
        _row(["---"] * 9),
    ]
    for name, metrics in results["dip"]:
        lines.append(_row([
            name,
            pct(metrics.get("cagr")),
            pct(metrics.get("vol")),
            num(metrics.get("sharpe")),
            pct(metrics.get("max_drawdown")),
            f"{metrics.get('worst_year')} {pct(metrics.get('worst_year_return'))}",
            num(metrics.get("ir_t")),
            num(metrics.get("dsr")),
            num(metrics.get("turnover_per_year"), 1),
        ]))
    lines += ["", "## Verdict", "", _verdict(results), "", "## Caveats", ""]
    lines.extend(f"- {item}" for item in results["caveats"])
    lines.append("")
    return "\n".join(lines)


def _verdict(results: dict) -> str:
    rec = results["recommendation"]
    headline = dict(results["headline"])
    desk = headline["desk_50_50"]
    wf = headline["walk_forward"]
    spy = headline["BH_SPY"]
    matched = headline["BH_SPY_walk_window"]
    final = headline.get("trend_core")
    action = rec["action"]
    base = (
        f"From {results['sample']['start']} to {results['sample']['end']}, "
        f"SPY compounded at {pct(spy['cagr'])} with a maximum drawdown of {pct(spy['max_drawdown'])} "
        f"and a worst year of {spy['worst_year']} ({pct(spy['worst_year_return'])}). "
        f"The desk's 50/50 mix, which is one pre-specified cell and not a walk-forward pick, "
        f"compounded at {pct(desk['cagr'])} with volatility {pct(desk['vol'])}, "
        f"Sharpe {num(desk['sharpe'])}, max drawdown {pct(desk['max_drawdown'])} "
        f"({desk.get('maxdd_trough')}), worst year {desk['worst_year']} ({pct(desk['worst_year_return'])}), "
        f"and an information-ratio t-stat of {num(desk['ir_t'])} against a multiple-testing bar of "
        f"{num(results['multiple_testing_bar_t'])}. Its deflated Sharpe is {num(desk['dsr'])}. "
        f"The same mix on listed UPRO after inception (synthetic before) compounded at "
        f"{pct(dict(results['headline'])['desk_50_50_stitched']['cagr'])}. "
        f"The walk-forward path, from {wf.get('start')} to {wf.get('end')}, compounded at {pct(wf['cagr'])} "
        f"against SPY at {pct(matched['cagr'])} over those same sessions, with max drawdown {pct(wf['max_drawdown'])}, "
        f"Sharpe {num(wf['sharpe'])}, IR t {num(wf['ir_t'])}, and deflated Sharpe {num(wf['dsr'])}. "
        f"The rule's current selection is `{rec['live_variant']}`."
    )
    if final:
        stitched = headline.get("trend_core_stitched") or {}
        base += (
            f" The final spec adds the three-down-close overlay on the SPY half only. "
            f"That book compounded at {pct(final['cagr'])} with volatility {pct(final['vol'])}, "
            f"Sharpe {num(final['sharpe'])}, max drawdown {pct(final['max_drawdown'])}, "
            f"worst year {final['worst_year']} ({pct(final['worst_year_return'])}), "
            f"and an information-ratio t-stat of {num(final['ir_t'])}. "
            f"On listed SSO and UPRO after each inception it compounded at {pct(stitched.get('cagr'))}. "
            "This is a pre-specified book, not a walk-forward selection."
        )
    if action == "trade_walk_forward":
        ending = (
            " The edge survives the precommitted bar: the walk-forward path beat SPY, "
            "its t-stat cleared the ledger's multiple-testing bar, and its deflated Sharpe is at least 0.95. "
            f"The recommended book is `{rec['variant']}`."
        )
    elif action == "unproven_walk_forward":
        ending = (
            " The edge does not survive. The walk-forward path beat SPY, but it did not clear "
            "the multiple-testing bar and the 0.95 deflated-Sharpe requirement together. "
            f"`{rec['live_variant']}` is what the rule would hold now; it is not a confirmed edge. "
            "The skeptical default is SPY. `signals_flagship.json` carries the rule's weights and is marked not endorsed. "
            "`signals.json` is still the fixed 50/50 trend-core book the paper bot already reads."
        )
    else:
        ending = (
            " The edge does not survive. The walk-forward path did not beat SPY, so the recommendation is 100% SPY. "
            "`signals.json` remains the fixed trend-core book; `signals_flagship.json` is SPY only."
        )
    return base + ending
