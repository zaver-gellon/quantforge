"""Markdown tearsheet. Every number is taken from the results payload."""

from __future__ import annotations


def pct(value, digits: int = 1) -> str:
    if value is None:
        return "n/a"
    try:
        if value != value:
            return "n/a"
    except TypeError:
        return "n/a"
    return f"{value * 100:.{digits}f}%"


def num(value, digits: int = 2) -> str:
    if value is None:
        return "n/a"
    try:
        if value != value:
            return "n/a"
    except TypeError:
        return "n/a"
    return f"{value:.{digits}f}"


def _row(cells) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def render_report(results: dict) -> str:
    lines = [
        "# Apex",
        "",
        "Generated by `python studies/apex/run.py`. Every figure comes from that run.",
        "The recommendation is the walk-forward path that cleared the precommitted bar.",
        "A full-sample ranking is a map of what was tested, not a pick.",
        "",
        results["protocol_md"],
        "",
        "## Sample",
        "",
        f"- Core sessions: {results['sample']['start']} to {results['sample']['end']} ({results['sample']['n_days']} days).",
        f"- Universe: {', '.join(results['universe'])}.",
        f"- Dropped: {', '.join(results['dropped']) or 'none'}.",
        f"- Trials counted toward deflation, including earlier studies: {results['n_trials']}.",
        f"- Multiple-testing bar (expected maximum |t|): {num(results['multiple_testing_bar_t'])}.",
        f"- Daily-Sharpe dispersion: {results['sharpe_dispersion_daily']:.4f}.",
        "",
        "## Does the walk-forward book beat SPY and the trend core?",
        "",
        "Same sessions, after costs. Trend-core is the final 2% hysteresis book with the dip on the SPY half only.",
        "",
        _row(["book", "CAGR", "vol", "Sharpe", "max DD", "IR t vs SPY", "DSR", "5y P(>SPY)", "5y P(>trend)"]),
        _row(["---"] * 9),
    ]
    for row in results["horse_race"]:
        lines.append(_row([
            row["name"],
            pct(row["cagr"]),
            pct(row["vol"]),
            num(row["sharpe"]),
            pct(row["max_drawdown"]),
            num(row.get("ir_t")),
            num(row.get("dsr")),
            num(row.get("p_beats_spy")),
            num(row.get("p_beats_trend")),
        ]))
    lines += [
        "",
        results["verdict"],
        "",
        "## Walk-forward paths",
        "",
        _row(["track", "live variant", "CAGR", "Sharpe", "max DD", "beats SPY", "beats trend", "survives"]),
        _row(["---"] * 8),
    ]
    for row in results["tracks"]:
        lines.append(_row([
            row["track"],
            row["live_variant"],
            pct(row["cagr"]),
            num(row["sharpe"]),
            pct(row["max_drawdown"]),
            "yes" if row["beats_spy"] else "no",
            "yes" if row["beats_trend"] else "no",
            "yes" if row["survives"] else "no",
        ]))
    lines += ["", "## What the primary rule held", ""]
    for track in results["tracks"]:
        lines.append(f"### {track['track']}")
        lines.append("")
        lines.append(_row(["year", "variant"]))
        lines.append(_row(["---", "---"]))
        for year, name in track["picks"]:
            lines.append(_row([year, name]))
        lines.append("")
        lines.append(_row(["variant", "years"]))
        lines.append(_row(["---", "---"]))
        for name, count in track["frequency"]:
            lines.append(_row([name, count]))
        lines.append("")
    lines += [
        "## Which components added value",
        "",
        "Each row is a fixed, precommitted book on the same out-of-sample sessions as the primary walk-forward.",
        "A component added value when removing it cut the equal-risk Sharpe by at least 0.02.",
        "Machine learning added value when its fixed path beat equal-risk by at least 0.05.",
        "This table does not choose the recommendation.",
        "",
        _row(["component", "Sharpe with it", "Sharpe without it", "delta", "added value"]),
        _row(["---"] * 5),
    ]
    for row in results["components"]:
        lines.append(_row([
            row["name"],
            num(row["sharpe_full"]),
            num(row["sharpe_without"]),
            num(row["delta"]),
            "yes" if row["added"] else "no",
        ]))
    lines += [
        "",
        "## Standalone alphas",
        "",
        "Long/short risk-budget book for that score alone, after costs, on the same out-of-sample sessions.",
        "",
        _row(["alpha", "CAGR", "Sharpe", "max DD"]),
        _row(["---"] * 4),
    ]
    for row in results["standalone"]:
        lines.append(_row([row["name"], pct(row["cagr"]), num(row["sharpe"]), pct(row["max_drawdown"])]))
    lines += ["", "## Stress", ""]
    lines.append(_row(["window", "book", "total return", "max DD", "days"]))
    lines.append(_row(["---"] * 5))
    for row in results["stress"]:
        lines.append(_row([
            row["window"], row["book"], pct(row["total"]), pct(row["max_drawdown"]), row["days"],
        ]))
    lines += [
        "",
        "## Block bootstrap of the walk-forward paths, $5,000",
        "",
        f"Circular blocks of {results['bootstrap_block']} sessions, {results['bootstrap_paths']} paths, seed {results['bootstrap_seed']}.",
        "",
        _row(["track", "horizon", "median", "p10", "p90", "P(loss)", "P(>SPY)", "P(>trend)"]),
        _row(["---"] * 8),
    ]
    for row in results["bootstrap_rows"]:
        lines.append(_row([
            row["track"], row["horizon"],
            f"${row['median']:,.0f}", f"${row['p10']:,.0f}", f"${row['p90']:,.0f}",
            num(row["p_loss"]), num(row.get("p_beats_spy")), num(row.get("p_beats_trend")),
        ]))
    cpcv = results.get("cpcv") or {}
    lines += [
        "",
        "## Combinatorial purged splits",
        "",
        "Contiguous groups of the out-of-sample path. This does not refit the book.",
        "",
    ]
    if cpcv:
        for name, block in cpcv.items():
            lines.append(
                f"- {name}: {block.get('n_splits', 0)} splits, median Sharpe {num(block.get('median'))}, "
                f"p10 {num(block.get('p10'))}, p90 {num(block.get('p90'))}, "
                f"fraction positive {num(block.get('fraction_positive'))}."
            )
    cap = results.get("capacity") or {}
    lines += ["", "## Capacity and turnover", ""]
    if cap:
        lines.append(
            f"Reference account ${cap['aum']:,.0f}. Median one-way impact on rebalance trades is "
            f"{cap['median_impact_bps']:.2f} bps. At ${cap['stress_aum']:,.0f} the same trades cost "
            f"{cap['stress_median_impact_bps']:.2f} bps, and the equal-risk long book CAGR moves from "
            f"{pct(cap['base_cagr'])} to {pct(cap['stress_cagr'])}."
        )
        lines.append("")
        lines.append(
            f"SPY median ADV ${cap['spy_adv']:,.0f}. A single SPY order costs 10 bps of impact near "
            f"${cap['spy_capacity_10bps']:,.0f} of notional."
        )
        lines.append("")
        lines.append(f"Primary path turnover is {num(cap.get('turnover_per_year'), 1)} times capital per year.")
    if results.get("regime"):
        lines += ["", "## Return by volatility/trend regime", "", _row(["regime", "days", "mean daily", "total"]), _row(["---"] * 4)]
        for row in results["regime"]:
            lines.append(_row([row["regime"], row["days"], f"{row['mean'] * 100:.3f}%", pct(row["total"])]))
    lines += [
        "",
        "## In-sample map (not a recommendation)",
        "",
        _row(["variant", "eligible", "CAGR", "Sharpe", "max DD"]),
        _row(["---"] * 5),
    ]
    for row in results["insample"]:
        lines.append(_row([
            row["name"], "yes" if row["eligible"] else "no",
            pct(row["cagr"]), num(row["sharpe"]), pct(row["max_drawdown"]),
        ]))
    lines += ["", "## Caveats", ""]
    for note in results["caveats"]:
        lines.append(f"- {note}")
    lines.append("")
    return "\n".join(lines)
