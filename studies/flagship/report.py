"""Render the flagship write-up from the results object. No numbers are typed in here."""

from __future__ import annotations

import math


def pct(value, digits: int = 1) -> str:
    if value is None or isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        return "n/a"
    return f"{100.0 * value:.{digits}f}%"


def num(value, digits: int = 2) -> str:
    if value is None or isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        return "n/a"
    return f"{value:.{digits}f}"


def money(value) -> str:
    if value is None or not isinstance(value, (int, float)) or not math.isfinite(value):
        return "n/a"
    return f"${value:,.0f}"


def _row(cells) -> str:
    return "| " + " | ".join(str(cell) for cell in cells) + " |"


def render_report(results: dict) -> str:
    lines = [
        "# Flagship: growth under a drawdown budget",
        "",
        "Generated by `python studies/flagship/run.py`. Every figure comes from that run.",
        "The recommendation is an out-of-sample path. Full-sample rows are a map of what was tested, not a pick.",
        "",
        results["protocol_md"].strip(),
        "",
        "## Sample",
        "",
        f"- Basket sessions: {results['sample']['start']} to {results['sample']['end']} "
        f"({results['sample']['n_days']} days).",
        f"- Walk-forward decisions start in {results['walk_forward_start']}. "
        f"A variant needs {results['min_obs']} prior sessions.",
        f"- Trials counted toward deflation, including earlier studies in the same ledger: {results['n_trials']}. "
        f"Multiple-testing bar (expected maximum |t|): {num(results['multiple_testing_bar_t'])}. "
        f"Daily-Sharpe dispersion: {num(results['sharpe_dispersion_daily'], 4)}.",
        f"- Universe actually used: {', '.join(results['universe'])}.",
        f"- Dropped for missing or thin history: {', '.join(results['dropped']) or 'none'}.",
        "",
        "## Out-of-sample frontier",
        "",
        "Each row is a stitched path. At each January the rule saw only earlier returns. "
        "The growth rule maximizes trailing CAGR among variants whose expanding-window max drawdown was inside the cap. "
        "The Sharpe row maximizes trailing excess Sharpe and ignores the cap. "
        "Realized drawdown can breach a cap that was satisfied in the past.",
        "",
        _row(["track", "OOS CAGR", "OOS vol", "OOS Sharpe", "OOS max DD", "vs SPY", "IR t", "DSR", "5y P(>SPY)", "5y P(loss)", "survives"]),
        _row(["---"] * 11),
    ]
    for row in results["frontier"]:
        lines.append(_row([
            row["track"],
            pct(row["cagr"]),
            pct(row["vol"]),
            num(row["sharpe"]),
            pct(row["max_drawdown"]),
            pct(row["spy_cagr"]),
            num(row["ir_t"]),
            num(row["dsr"]),
            num(row.get("p_beats_spy")),
            num(row.get("p_loss")),
            "yes" if row["survives"] else "no",
        ]))
    lines += [
        "",
        "## Verdict",
        "",
        results["verdict"],
        "",
        "## What the growth rule held",
        "",
    ]
    for track in results["picks"]:
        lines.append(f"### {track['track']}")
        lines.append("")
        lines.append(_row(["year", "variant"]))
        lines.append(_row(["---", "---"]))
        for year, name in track["picks"]:
            lines.append(_row([year, name]))
        lines.append("")
        if track.get("frequency"):
            lines.append(_row(["variant", "years"]))
            lines.append(_row(["---", "---"]))
            for name, count in track["frequency"]:
                lines.append(_row([name, count]))
            lines.append("")
    lines += [
        "## In-sample map (not a recommendation)",
        "",
        "Sorted by full-sample CAGR. A name at the top of this table was not selected by the walk-forward rule "
        "unless it also appears in the frontier. Stock-level momentum is ineligible for the recommendation because "
        "the universe is today's survivors.",
        "",
        _row(["variant", "family", "eligible", "CAGR", "vol", "Sharpe", "max DD", "IR t"]),
        _row(["---"] * 8),
    ]
    for row in results["insample"]:
        lines.append(_row([
            row["name"],
            row["family"],
            "yes" if row["eligible"] else "no",
            pct(row["cagr"]),
            pct(row["vol"]),
            num(row["sharpe"]),
            pct(row["max_drawdown"]),
            num(row.get("ir_t")),
        ]))
    lines += ["", "## Block bootstrap of the out-of-sample paths, $5,000", ""]
    lines.append(
        f"Circular blocks of {results['bootstrap_block']} sessions, {results['bootstrap_paths']} paths, "
        f"seed {results['bootstrap_seed']}. The SPY blocks are the same draws."
    )
    lines += [
        "",
        _row(["track", "1y median", "1y p10", "1y p90", "1y P(loss)", "5y median", "5y p10", "5y p90", "5y P(loss)", "5y P(>SPY)", "5y P(<-30%)"]),
        _row(["---"] * 11),
    ]
    for row in results["frontier"]:
        boot = row.get("bootstrap") or {}
        y1, y5 = boot.get("1y") or {}, boot.get("5y") or {}
        lines.append(_row([
            row["track"],
            money(y1.get("median")), money(y1.get("p10")), money(y1.get("p90")), num(y1.get("p_loss")),
            money(y5.get("median")), money(y5.get("p10")), money(y5.get("p90")), num(y5.get("p_loss")),
            num(y5.get("p_beats_benchmark")), num(y5.get("p_down_30")),
        ]))
    if results.get("validation"):
        lines += [
            "",
            "## Leveraged-ETF check",
            "",
            "Synthetic sleeves use the same daily-reset model as the trend study. Where a listed fund was downloaded, "
            "this is the overlap. A wide gap means the financed multiple is a model, not the fund.",
            "",
            _row(["ETF", "days", "actual CAGR", "synth CAGR", "corr", "TE"]),
            _row(["---"] * 6),
        ]
        for row in results["validation"]:
            lines.append(_row([
                row.get("etf"),
                row.get("n_days"),
                pct(row.get("actual_cagr")),
                pct(row.get("synthetic_cagr")),
                num(row.get("daily_corr"), 3),
                pct(row.get("tracking_error")),
            ]))
    lines += ["", "## Caveats", ""]
    lines.extend(f"- {item}" for item in results["caveats"])
    lines.append("")
    return "\n".join(lines)
